// Template for selectable item collections, such as weapon slots and vehicle stations.
// [INFERRED] source placement.

#ifndef GAME_OBJECTS_ITEMCONTAINERTEMPLATE_H     // [INFERRED] guard style
#define GAME_OBJECTS_ITEMCONTAINERTEMPLATE_H

#include "Base/BundleTemplate.h"
#include "IItemTemplate.h"

#include <list>

namespace dice {
namespace hfe {
namespace world {

class ItemContainerTemplate : public BundleTemplate, public IItemTemplate
{
public:
    ItemContainerTemplate();

    virtual void addRef();
    virtual int getRef();
    virtual int release();
    virtual void* queryInterface(unsigned int iid) const;
    virtual unsigned int getClassID() const;
    virtual ~ItemContainerTemplate();
    virtual void* queryImplementation(unsigned int classId);
    virtual IObject* createObject() const;
    virtual void setItemIndex(int itemIndex);
    virtual int getItemIndex() const;
    virtual void setItemType(int itemType);
    virtual int getItemType() const;

    void setIndex(int index);
    void replaceItem(const std::string& item);

    // Kit reads unlock level and item contents directly.
    friend class Kit;
    friend class KitTemplate; // getHighestUnlockLevel reads the same shipped field directly
    friend struct GameTemplateConsoleAccess;  // recovered ObjectTemplate.unlockLevel executor

protected:
    // layout, offsets 380..407. BundleTemplate occupies 0..379.
    // The IItemTemplate vptr at +380 is compiler-generated by the real secondary base above.
    /* 384 */ int   m_refCount3;
    /* 388 */ int   m_index;
    /* 392 */ int   m_itemIndex;
    /* 396 */ int   m_itemType;
    /* 400 */ int   m_unlockLevel;                   // was `_dword190`; .con property `unlockLevel`
    /* 404 */ std::list<std::string> m_items;         // old-GCC object is one sentinel pointer
};

} // namespace world
} // namespace hfe
} // namespace dice

#endif // GAME_OBJECTS_ITEMCONTAINERTEMPLATE_H
