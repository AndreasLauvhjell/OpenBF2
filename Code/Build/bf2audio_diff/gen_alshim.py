"""[TEMP] [CHOSEN, not recovered] - SCAFFOLDING. Generates the pass-through half of the OpenAL logging
shim (alshim_tramp.cpp + alshim.def) from the retail wrap_oal's export list: every export the shim
does not wrap explicitly becomes a naked `jmp` through a pointer resolved from the real DLL, so the
shim exposes wrap_oal's whole surface without knowing every signature.

usage: gen_alshim.py <exports.txt> <out dir>"""
import sys, os

WRAPPED = """alGetInteger alGetString alGetError alIsExtensionPresent alGetProcAddress alGetEnumValue
alListenerf alListenerfv alListener3f alGetListenerfv alGenSources alDeleteSources alSourcei alSourcef
alSourcefv alGetSourcei alGetSourcef alGetSourcefv alSourcePlay alSourceStop alSourceRewind alGenBuffers
alDeleteBuffers alBufferData alGetBufferi alSourceUnqueueBuffers alSourceQueueBuffers alDopplerFactor
alDistanceModel alcCreateContext alcMakeContextCurrent alcDestroyContext alcGetError alcOpenDevice
alcCloseDevice alcIsExtensionPresent alcGetString alcGetIntegerv EAXSet EAXGet""".split()

exports = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out = sys.argv[2]
tramp = [e for e in exports if e not in WRAPPED]

with open(os.path.join(out, "alshim_tramp.cpp"), "w") as f:
    f.write("// GENERATED by gen_alshim.py - do not edit. Naked pass-throughs for the exports the shim does not wrap.\n")
    f.write("#include \"alshim.h\"\n\n")
    for e in tramp:
        f.write("void* p_%s = 0;\n" % e)
    f.write("\nvoid resolveTrampolines(void* (*resolve)(const char*))\n{\n")
    for e in tramp:
        f.write("    p_%s = resolve(\"%s\");\n" % (e, e))
    f.write("}\n\n")
    for e in tramp:
        f.write("extern \"C\" __declspec(naked) void %s() { __asm { call ensureLoaded } __asm { jmp dword ptr [p_%s] } }\n" % (e, e))

with open(os.path.join(out, "alshim.def"), "w") as f:
    f.write("LIBRARY BF2OpenAL\nEXPORTS\n")
    for e in exports:
        f.write("    %s\n" % e)
    f.write("    alshim_mark\n")
print("trampolines: %d, wrapped: %d, exports: %d" % (len(tramp), len(WRAPPED), len(exports) + 1))
