// Stores all gameplay objects in Editor/GamePlayObjects.con with metadata in Editor/Layer.con.
// Generates mode/player buckets from enabled layers whose filters match; preserves host blocks and writer order.
// Import retains only buckets it can regenerate byte-for-byte and reports others without modifying them.
// [CHOSEN] Writes a bucket only when a non-Default layer fills it or its file already exists.
#ifndef BF2EDITOR_FRAMEWORK_GAMEPLAYLAYERS_H
#define BF2EDITOR_FRAMEWORK_GAMEPLAYLAYERS_H

#include "Framework/EditorConfig.h"

#include <set>
#include <string>
#include <utility>
#include <vector>

namespace bf2editor
{

// The mod's filters (bf2editor/mods/<mod>/LayerInit.con: LayerManager.CreateDefaultFilter <id> <label>,
// LayerManager.CreateDefaultPlayerFilter <count>).
struct GameplayFilters
{
    std::vector<std::string> modes;         // gpm_cq, gpm_sl, gpm_coop, sp1, sp2, sp3
    std::vector<std::string> modeLabels;    // Conquest, SupplyLine, Coop, SP1, SP2, SP3
    std::vector<std::string> players;       // 16, 32, 64
    static GameplayFilters defaults();      // the stock bf2 LayerInit.con
    bool parse(const std::string& text);    // false when the text names no filter
    void addMode(const std::string& id, const std::string& label);
    void addPlayers(const std::string& count);
};

struct GameplayLayer
{
    int                      id = 1;        // 1 is the Default: every filter, never written to Layer.con
    std::string              name;
    bool                     visible = true;
    bool                     locked = false;
    bool                     disabled = false;  // left out of every game-mode file (still loaded and edited)
    std::vector<std::string> modes;         // its filters
    std::vector<std::string> players;
    bool takes(const std::string& mode, const std::string& count) const;
};

// Parses or writes Editor/Layer.con blocks for non-default layers, including visibility,
// lock/disable state, game-mode filters, and player-count filters.
bool parseLayerFile(const std::string& text, std::vector<GameplayLayer>& layers, std::string& error);
std::string renderLayerFile(const std::vector<GameplayLayer>& layers);

enum class GameplaySection { Spawner, SpawnPoint, ControlPoint, CombatArea };

struct GameplayObject
{
    GameplaySection          section = GameplaySection::Spawner;
    std::string              name;          // the template's name; the area's
    std::vector<std::string> templateLines; // its template block, banner first (none for an area)
    std::vector<std::string> instanceLines; // its instance block (an area's whole block), banner first
    int                      layer = 1;     // Object.layer / CombatArea.layer
};

class GameplaySet
{
public:
    bool parse(const std::string& text, std::string& error);
    // The file of the objects whose layer `include` holds (every object for an empty `include` and `all`).
    std::string render(const std::set<int>& include, bool all) const;
    const std::vector<GameplayObject>& objects() const { return m_objects; }
    std::vector<GameplayObject>& objects() { return m_objects; }
    std::vector<std::string>& manager() { return m_manager; }
    const std::vector<std::string>& manager() const { return m_manager; }
    // Lines above the sections (a level's own, kept as they are).
    std::vector<std::string>& preamble() { return m_preamble; }
    const std::vector<std::string>& preamble() const { return m_preamble; }
    int find(GameplaySection section, const std::string& name) const;   // its index, -1 for none
    // Orders: templates and instances of spawners and control points may differ; spawn points are pairs.
    std::vector<int> templateOrder[4];
    std::vector<int> instanceOrder[4];
    std::string      newline = "\r\n";

private:
    std::vector<GameplayObject> m_objects;
    std::vector<std::string>    m_manager;
    std::vector<std::string>    m_preamble;
};

// One game-mode file of a level.
struct GameplayBucket
{
    std::string mode;
    std::string players;
    std::string text;
};

struct GameplayImport
{
    GameplaySet                                      set;        // the union of the buckets kept
    std::vector<GameplayLayer>                       layers;     // rebuilt: ids from the files, filters from the buckets
    std::vector<std::pair<std::string, std::string>> managed;    // (mode, players) regenerated byte for byte
    std::vector<std::pair<std::string, std::string>> unmanaged;  // left as they are
    std::vector<std::string>                         notes;      // why each was left
};

// The editor set rebuilt from a level's game-mode files (see above).
bool importBuckets(const std::vector<GameplayBucket>& buckets, const GameplayFilters& filters, GameplayImport& result);
// The game-mode file the layers make for (mode, players): "" when no layer reaches it.
std::string renderBucket(const GameplaySet& set, const std::vector<GameplayLayer>& layers, const std::string& mode,
                         const std::string& players);
// Whether a bucket is written: a layer other than the Default fills it, or its file exists (`exists`).
bool bucketWritten(const GameplaySet& set, const std::vector<GameplayLayer>& layers, const std::string& mode,
                   const std::string& players, bool exists);

} // namespace bf2editor

#endif // BF2EDITOR_FRAMEWORK_GAMEPLAYLAYERS_H
